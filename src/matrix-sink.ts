/**
 * Matrix notification delivery sink (WR-246).
 *
 * Some downstreams are not queues, streams, or topics at all:
 * they are a human's chat room. Where the Pushbullet sink
 * (WR-245) delivers to a Pushbullet account, this sink
 * delivers to a Matrix room: one event is posted as one
 * `m.room.message` event to the room, and Matrix — not the
 * relay — owns the room, the delivery, and the retention
 * of the message.
 *
 * No real HTTP client is bundled: the client is injected
 * through `config.client` (a thin adapter over whatever HTTP
 * the operator runs — `fetch`, a sidecar), so the module has
 * zero new dependencies and tests never need a Matrix
 * server. The sink owns the relay-side concerns — room
 * targeting, message-text derivation, payload-inclusion
 * policy, per-message failure mapping — and the injected
 * client owns the wire protocol, including the POST call,
 * the authentication, the transaction id, and the status it
 * returns.
 *
 * Wire shape — one POST per message, carried to the
 * injected client as:
 *
 *   { homeserver: "<homeserver>",
 *     roomId: "<room-id>",
 *     body: "{\"msgtype\":\"m.text\",\"body\":\"<body>\"}" }
 *
 * The client POSTs to
 * `{homeserver}/_matrix/client/v3/rooms/{roomId}/send/m.room.message/{txnId}`,
 * with `body` verbatim as the request body (a JSON object,
 * not plain text) and an `Authorization: Bearer` header
 * carrying its own access token. Two things about this
 * shape differ from every sibling sink, and both are
 * deliberate:
 *
 * - The access token is held by the client alone. The sink
 *   never receives it, never places it in the request, and
 *   never logs it: unlike the Pushbullet sink, whose token
 *   rides in a request header the sink builds, the Matrix
 *   sink's request carries no credential at all — there is
 *   nothing in it for a log line or a retry queue to leak.
 * - The transaction id is generated by the client, not the
 *   sink. Matrix deduplicates redelivered events by txnId,
 *   so the id must be unique per POST attempt and stable
 *   across that attempt's retries — a property only the
 *   component that actually performs the POST can honour,
 *   since it alone knows whether an attempt went out. The
 *   sink therefore hands the client the room and the
 *   message, and the client owns the id.
 *
 * The homeserver is configurable, unlike the fixed hosts
 * of the Pushover and Pushbullet sinks: Matrix is a
 * federated protocol, so the operator's homeserver varies
 * (matrix.org, a company server, a self-hosted one). The
 * room id is likewise configured: one sink targets one
 * room. A missing homeserver or room id is a config error,
 * not a resolution fallback: unlike the broker sinks,
 * there is no per-record target to resolve to, so a sink
 * with no room has nowhere to deliver and fails closed
 * with `MatrixSinkConfigError` at send time (dry runs
 * excepted — they need no room at all, mirroring the
 * sibling sinks' dry-run exemption for the client).
 *
 * Message text — derived from the event's own values.
 * Matrix's `m.room.message` event carries a single text
 * field, so where the sibling sinks split the text into a
 * title and a body, this sink folds the derivation chain
 * into one: the first non-empty value among `subject`,
 * `key`, and `traceId`, in that order. The subject is what
 * the event is about, the key (e.g. aggregate id) is the
 * next most identifying value, and the trace id names the
 * trace that produced the event. An event with none of the
 * values still notifies, with the generic summary `webhook
 * event`: a notification sink that silently dropped
 * sourceless events would hide exactly the deliveries an
 * operator most needs to see, and the room id — not the
 * text — is the delivery contract here, so no invented
 * target is at stake.
 *
 * Payload inclusion — by default the message carries the
 * summary only, never the full payload: event bodies
 * routinely carry PII, secrets, or customer data, and a
 * chat room is a far wider audience than a queue or a
 * stream. Opting into `includePayload` appends the body
 * verbatim after a blank line, truncated to
 * `payloadMaxChars` characters (default 2000) with a
 * truncation marker — the opt-in is explicit, and the
 * truncation is unconditional, so even an opted-in body
 * cannot flood a room or blow past Matrix's message
 * limits. The body is appended as plain text inside the
 * `body` field, not a fenced code block: Matrix renders
 * `m.text` as-is, and a fence would be noise in a room.
 *
 * Failure handling mirrors the WR-210 SQS sink's
 * classification (`src/failure.ts`), applied per message
 * over HTTP status:
 *
 * - a non-2xx POST throws `MatrixSinkError` carrying
 *   every failed message with its retry lane already
 *   mapped, so the caller retries exactly the failed
 *   messages;
 * - retryable statuses are the transient HTTP states —
 *   429 and every 5xx: a rate limit says Matrix could
 *   not accept the message right now, not that the
 *   payload is poison;
 * - non-retryable statuses are the fail-closed messages
 *   — every other non-2xx status, including 400, 401,
 *   403, and 404 (unknown room, invalid body): retrying
 *   them burns the retry budget for nothing, and
 *   rerouting them elsewhere would notify a room the
 *   operator never chose;
 * - a codeless transport failure (the client threw) is
 *   retryable, like an SQS transport error with no status:
 *   it says nothing about the payload;
 * - a missing client, homeserver, or room id throws
 *   `MatrixSinkConfigError`, which `classifyFailure`
 *   maps to `non_retryable` (the WR-116 rule).
 *
 * Zero new dependencies: the injected client only.
 */

/** Generic summary used when an event carries no value for the text field. */
export const MATRIX_FALLBACK_SUMMARY = "webhook event";

/** Default truncation limit for an opted-in payload snippet, in characters. */
export const MATRIX_DEFAULT_PAYLOAD_MAX_CHARS = 2000;

/** Fixed Matrix message type for every notification (a plain-text message). */
export const MATRIX_MESSAGE_TYPE = "m.text";

/** Matrix client API path segment for sending a room message (the client appends the txnId). */
export const MATRIX_SEND_PATH = "/_matrix/client/v3/rooms";

/**
 * One POST request as handed to the injected client. The
 * client owns the wire protocol: it POSTs to
 * `{homeserver}/_matrix/client/v3/rooms/{roomId}/send/m.room.message/{txnId}`
 * (generating the txnId itself), sends `body` verbatim as
 * the request body (the JSON object with `msgtype` and
 * `body`), and authenticates with an `Authorization: Bearer`
 * header carrying an access token it alone holds. The sink
 * never sees that token, so the request carries no
 * credential: nothing here can leak into a log line. The
 * homeserver is passed with trailing slashes stripped, so
 * the client's path concatenation cannot double a slash.
 */
export interface MatrixMessagePostRequest {
  /** The operator's homeserver base URL, trailing slashes stripped. */
  homeserver: string;
  /** The target room id (e.g. `!roomid:matrix.org`). */
  roomId: string;
  /** The JSON message object, serialized: msgtype "m.text", body. */
  body: string;
}

/**
 * The result of one POST, as reported by the injected client.
 * Only the status matters to the sink's retry mapping; the
 * client need not parse Matrix's response body.
 */
export interface MatrixMessagePostResponse {
  /** The HTTP status of the POST (e.g. 200, 429, 503). */
  status: number;
}

/**
 * The injected Matrix message client. Any client adapter
 * implements this one method; it returns the POST's status
 * (a throw is a codeless transport failure, retryable). The
 * client is expected to POST one message per call, sending
 * `body` verbatim as the request body (the JSON object with
 * `msgtype` and `body`), generating its own txnId, and
 * authenticating with its own access token — none of which
 * the sink ever sees.
 */
export interface MatrixMessageClient {
  post(request: MatrixMessagePostRequest): Promise<MatrixMessagePostResponse>;
}

/**
 * Configuration for one Matrix sink. The client is
 * injected: without one, `send()` throws
 * `MatrixSinkConfigError` (dry runs excepted — they need
 * no client at all). A missing homeserver or room id is
 * likewise a config error at send time (dry runs
 * excepted): there is no per-record target to fall back
 * to.
 */
export interface MatrixSinkConfig {
  /**
   * The operator's homeserver base URL (e.g.
   * `https://matrix.org`). Matrix is federated, so this
   * varies per deployment — unlike the fixed hosts of the
   * Pushover and Pushbullet sinks. Must be a non-empty
   * string, free of NUL and whitespace, when set; a
   * missing homeserver throws `MatrixSinkConfigError` at
   * send time, never a silent no-op.
   */
  homeserver?: string;
  /**
   * The target room id: the recipient of every message
   * from this sink. Must be a non-empty string, free of
   * NUL and whitespace, when set; a missing room id
   * throws `MatrixSinkConfigError` at send time.
   */
  roomId?: string;
  /**
   * The Matrix message client to deliver through.
   * Injected, never bundled: the operator's client adapter
   * implements `MatrixMessageClient` and alone holds the
   * access token and generates txnIds. Required for real
   * sends; a missing client is a config error, not a
   * silent no-op.
   */
  client?: MatrixMessageClient;
  /**
   * Rehearsal mode: `send()` returns
   * `{ ok: true, sent: 0, dryRun: true }` and performs zero
   * client I/O — no POST call, no stat changes. Messages are
   * still validated (including text derivation), so a dry run
   * catches a malformed record before it reaches production.
   * Mirrors the `dryRun` convention of the S3 offloaders.
   * The homeserver, room id, and client are not required in
   * dry-run mode, mirroring the sibling sinks' dry-run
   * exemption.
   */
  dryRun?: boolean;
  /**
   * Payload opt-in: when `true`, the message text appends
   * the event body verbatim after a blank line, truncated to
   * `payloadMaxChars` characters (see below). When `false`
   * or absent, the message carries the summary only — the
   * default, so event bodies (which routinely carry PII)
   * never leak into a notification unless the operator
   * explicitly asks for them.
   */
  includePayload?: boolean;
  /**
   * Truncation limit for an opted-in payload snippet, in
   * characters (default 2000). Only meaningful with
   * `includePayload`; the truncation is unconditional when
   * the opt-in is set, so an opted-in body cannot flood a
   * room. Must be a positive integer when set.
   */
  payloadMaxChars?: number;
}

/** One event to notify about. */
export interface MatrixRecord {
  /** The event JSON, already serialized by the caller — used only under the `includePayload` opt-in. */
  body: string;
  /**
   * Text-derivation source, first priority: the event's
   * subject, when set and non-empty. Falls through to `key`,
   * then `traceId`.
   */
  subject?: string;
  /**
   * Text-derivation source, second priority: the event's key
   * (e.g. aggregate id).
   */
  key?: string;
  /**
   * Text-derivation source, last priority: the trace id.
   */
  traceId?: string;
}

/** One failed message, with its retry lane already mapped. */
export interface MatrixFailedRecord {
  /** Index into the caller's original `records` array. */
  index: number;
  /** Failure code: `HTTP_<status>` for a non-2xx POST, or `TRANSPORT_ERROR` for a codeless failure. */
  errorCode: string;
  /** Downstream HTTP status, when the failure was a non-2xx POST. */
  statusCode?: number;
  /** Client error message, when the failure carried one. */
  errorMessage?: string;
  /**
   * Retry lane under the WR-210 mapping: 429 and 5xx (plus
   * codeless transport failures) are retryable, every other
   * non-2xx status is a fail-closed message (unknown room,
   * invalid body).
   */
  retryable: boolean;
}

/** Outcome of one `send()` call (failures throw, see above). */
export interface MatrixSendResult {
  /** Always `true` for a returned result — failures throw. */
  ok: true;
  /** Messages the client accepted (real sends only; 0 in dry-run mode). */
  sent: number;
  /** `true` only in dry-run mode: no client I/O happened. */
  dryRun?: boolean;
}

/** Introspection counters (WR-246). */
export interface MatrixSinkStats {
  /** Messages accepted by the client (real sends, not dry runs). */
  sent: number;
  /** Messages reported failed by the client. */
  failed: number;
  /** send calls that threw (counted before the error is thrown). */
  sendFailures: number;
}

/**
 * Thrown for Matrix send failures. Carries every failed
 * message with its retry lane (`failedRecords`), so the retry
 * queue can requeue exactly those messages. A send call that
 * throws has partial success behind it — the accepted messages
 * are already on the Matrix server and are *not* in
 * `failedRecords`.
 */
export class MatrixSinkError extends Error {
  /** Per-message failures, in input order, each with their retry lane. */
  readonly failedRecords: MatrixFailedRecord[];
  constructor(message: string, failedRecords: MatrixFailedRecord[]) {
    super(message);
    this.name = "MatrixSinkError";
    this.failedRecords = failedRecords;
  }
}

/**
 * Thrown when the sink cannot even send — currently: no
 * client was injected, or the homeserver or room id is
 * missing. A config problem, not a downstream verdict, so
 * the retry queue must not burn attempts on it
 * (`classifyFailure` maps it to `non_retryable`).
 */
export class MatrixSinkConfigError extends MatrixSinkError {
  constructor(reason: string) {
    super(`matrix-sink: ${reason}`, []);
    this.name = "MatrixSinkConfigError";
  }
}

/**
 * Validate a sink config. Throws `RangeError` on any bad shape —
 * called at startup so a typo fails fast, never mid-delivery. A
 * missing homeserver or room id is *not* a shape error: it is a
 * config error raised at send time (`MatrixSinkConfigError`),
 * so a sink built before its room is known still fails closed
 * at send time rather than crashing at construction. A present
 * homeserver or room id must be a non-empty string, free of
 * NUL and whitespace.
 */
export function assertValidMatrixSinkConfig(
  cfg: unknown,
  label: string
): asserts cfg is MatrixSinkConfig {
  const at = (what: string) => `${label}: ${what}`;
  if (cfg === null || typeof cfg !== "object") {
    throw new RangeError(at("config must be an object"));
  }
  const c = cfg as Record<string, unknown>;
  for (const field of ["homeserver", "roomId"] as const) {
    const value = c[field];
    if (value !== undefined) {
      if (
        typeof value !== "string" ||
        value === "" ||
        (value as string).includes("\0") ||
        /\s/.test(value as string)
      ) {
        throw new RangeError(
          at(`\`${field}\` must be a non-empty string, free of NUL and whitespace when set`)
        );
      }
    }
  }
  if (
    c.client !== undefined &&
    (c.client === null ||
      typeof c.client !== "object" ||
      typeof (c.client as { post?: unknown }).post !== "function")
  ) {
    throw new RangeError(at("`client` must expose a `post` function when set"));
  }
  if (
    c.payloadMaxChars !== undefined &&
    (typeof c.payloadMaxChars !== "number" ||
      !Number.isInteger(c.payloadMaxChars) ||
      c.payloadMaxChars <= 0)
  ) {
    throw new RangeError(at("`payloadMaxChars` must be a positive integer when set"));
  }
}

/**
 * Strip trailing slashes from a homeserver base URL, so the
 * client's path concatenation cannot double a slash. The
 * root `/` alone is not a usable homeserver and is left to
 * the client's URL handling — this helper only trims.
 */
export function normalizeMatrixHomeserver(homeserver: string): string {
  return homeserver.replace(/\/+$/, "");
}

/**
 * Derive one record's message text: the first non-empty
 * value among `subject`, `key`, and `traceId`, in that
 * order. Falls back to the generic `webhook event` summary
 * when the record carries none — a notification sink must
 * not silently drop sourceless events, and the room id
 * (not the text) is the delivery contract.
 */
export function resolveMatrixText(record: MatrixRecord): string {
  for (const value of [record.subject, record.key, record.traceId]) {
    if (value !== undefined && value !== "") {
      return value;
    }
  }
  return MATRIX_FALLBACK_SUMMARY;
}

/**
 * Truncate an opted-in payload snippet to `limit`
 * characters, appending a truncation marker when cut. The
 * truncation is unconditional under the opt-in, so an
 * opted-in body cannot flood a room.
 */
export function truncateMatrixPayload(body: string, limit: number): string {
  if (body.length <= limit) {
    return body;
  }
  return `${body.slice(0, limit)}… (truncated)`;
}

/**
 * Derive one record's notification text. Only under the
 * `includePayload` opt-in does the text append the event
 * body verbatim after a blank line, truncated to
 * `payloadMaxChars` (default 2000). Without the opt-in, the
 * text is the summary alone: event bodies routinely carry
 * PII and must never leak into a notification by default.
 * The body is appended as plain text inside the `body`
 * field, not a fenced code block: Matrix renders `m.text`
 * as-is, and a fence would be noise in a room.
 */
export function resolveMatrixNotification(
  record: MatrixRecord,
  config: Pick<MatrixSinkConfig, "includePayload" | "payloadMaxChars">
): { text: string } {
  let text = resolveMatrixText(record);
  if (config.includePayload === true) {
    const limit = config.payloadMaxChars ?? MATRIX_DEFAULT_PAYLOAD_MAX_CHARS;
    text = `${text}\n\n${truncateMatrixPayload(record.body, limit)}`;
  }
  return { text };
}

/**
 * Validate one record's body and resolve its send form: the
 * JSON message object, serialized. Throws `RangeError` on an
 * empty body string — even without the opt-in, the body is
 * the record's payload, and an empty record is a caller bug
 * that must fail closed, never notify as an empty message.
 * The serialized form carries no credential: the access
 * token is held by the client alone and never appears here.
 */
export function resolveMatrixRecord(
  record: MatrixRecord,
  index: number,
  config: Pick<MatrixSinkConfig, "includePayload" | "payloadMaxChars">
): { body: string; index: number } {
  if (typeof record.body !== "string" || record.body === "") {
    throw new RangeError(`matrix-sink: record ${index} \`body\` must be a non-empty event JSON string`);
  }
  const notification = resolveMatrixNotification(record, config);
  return {
    body: JSON.stringify({
      msgtype: MATRIX_MESSAGE_TYPE,
      body: notification.text,
    }),
    index,
  };
}

/**
 * Map one Matrix POST `statusCode` onto its retry lane under
 * the WR-210 rules: 429 and every 5xx are transient and so
 * retryable — a rate limit says Matrix could not accept
 * the message right now, not that the payload is poison.
 * Every other non-2xx status (400, 401, 403, 404, and the
 * rest) is a fail-closed message: unknown room, invalid
 * body, or another verdict retrying cannot change. Callers
 * only pass non-2xx statuses here; a 2xx status is a
 * success, not a failure.
 */
export function classifyMatrixRecordFailure(statusCode: number): boolean {
  return statusCode === 429 || statusCode >= 500;
}

/**
 * Matrix sink (WR-246). One instance targets one Matrix
 * room; the caller owns retry/dead-letter policy around
 * `send()` — this class performs one POST attempt per
 * message through the injected client and reports its
 * outcome. Failures throw `MatrixSinkError` carrying
 * exactly the failed messages with their retry lanes.
 */
export class MatrixSink {
  private readonly cfg: MatrixSinkConfig;
  private sent = 0;
  private failed = 0;
  private sendFailures = 0;

  constructor(config: MatrixSinkConfig) {
    assertValidMatrixSinkConfig(config, "MatrixSink");
    this.cfg = config;
  }

  /** Current counters; dry runs change none of them. */
  get stats(): MatrixSinkStats {
    return {
      sent: this.sent,
      failed: this.failed,
      sendFailures: this.sendFailures,
    };
  }

  /**
   * Send messages to the Matrix room, in input order. Throws
   * `MatrixSinkConfigError` when no client was injected or
   * the homeserver or room id is missing, and
   * `MatrixSinkError` when any message fails (carrying
   * exactly the failed messages with their retry lanes; both
   * counted in stats before throwing, so the counters stay
   * honest even for callers that only inspect stats).
   */
  async send(records: MatrixRecord[]): Promise<MatrixSendResult> {
    const resolved = records.map((r, i) => resolveMatrixRecord(r, i, this.cfg));
    if (this.cfg.dryRun === true) {
      // Validate even in rehearsal, so a dry run still catches
      // a malformed record before it reaches production — but
      // perform zero client I/O and touch no stats. The
      // homeserver, room id, and client are not required here,
      // mirroring the sibling sinks' dry-run exemption.
      return { ok: true, sent: 0, dryRun: true };
    }
    const client = this.cfg.client;
    if (client === undefined) {
      throw new MatrixSinkConfigError("no client injected (set `client` in the sink config)");
    }
    const homeserver = this.cfg.homeserver;
    if (homeserver === undefined) {
      throw new MatrixSinkConfigError("no homeserver configured (set `homeserver` in the sink config)");
    }
    const roomId = this.cfg.roomId;
    if (roomId === undefined) {
      throw new MatrixSinkConfigError("no room id configured (set `roomId` in the sink config)");
    }
    const failedRecords: MatrixFailedRecord[] = [];
    let sent = 0;
    for (const record of resolved) {
      try {
        const response = await client.post({
          homeserver: normalizeMatrixHomeserver(homeserver),
          roomId,
          body: record.body,
        });
        if (response.status >= 200 && response.status < 300) {
          sent += 1;
          continue;
        }
        failedRecords.push({
          index: record.index,
          errorCode: `HTTP_${response.status}`,
          statusCode: response.status,
          retryable: classifyMatrixRecordFailure(response.status),
        });
      } catch (err) {
        failedRecords.push(toMatrixFailedRecord(err, record.index));
      }
    }
    this.sent += sent;
    this.failed += failedRecords.length;
    if (failedRecords.length > 0) {
      this.sendFailures += 1;
      throw new MatrixSinkError(
        `matrix-sink: send failed for ${failedRecords.length} of ${resolved.length} messages`,
        failedRecords
      );
    }
    return { ok: true, sent };
  }
}

/**
 * Convert a client throw into a failed message: a codeless
 * transport failure (`TRANSPORT_ERROR`, retryable — the SQS
 * no-status rule).
 */
function toMatrixFailedRecord(err: unknown, index: number): MatrixFailedRecord {
  const failed: MatrixFailedRecord = {
    index,
    errorCode: "TRANSPORT_ERROR",
    retryable: true,
  };
  if (err instanceof Error && err.message !== "") {
    failed.errorMessage = err.message;
  }
  return failed;
}
